// Публичный ключ VAPID для браузера.
//
// Почему адресом, а не переменной сборки. Ключ нужен клиенту в момент подписки
// (applicationServerKey), и его можно было бы вшить в бандл через VITE_*. Но
// тогда ротация ключа требует пересборки и раскатки фронта, а до этого браузер
// подписывается на СТАРЫЙ ключ, и шлюз отвечает на посылки 403 — молча, для
// пользователя это просто «уведомления не приходят». Отдавая ключ с сервера,
// мы гарантируем, что клиент подписан ровно на тот ключ, которым сервер
// подписывает.
//
// Заодно это признак, видный снаружи: `{ok:true, push:false}` означает, что
// ключи не заданы и кнопка подписки в кабинете не показывается.

import { vapidKeys } from "../server/pushQueue.js"

export default async function handler(req, res) {
  if (req.method !== "GET") {
    res.setHeader("Allow", "GET")
    return res.status(405).json({ error: "method not allowed" })
  }
  const keys = vapidKeys()
  // Ключ публичный по назначению — он и так уезжает в браузер каждому
  // подписчику. Кэшировать надолго не стоит: после ротации клиенты должны
  // переподписаться в тот же день.
  res.setHeader("Cache-Control", "public, max-age=300")
  return res.status(200).json({ ok: true, push: !!keys, key: keys?.publicKey || null })
}
