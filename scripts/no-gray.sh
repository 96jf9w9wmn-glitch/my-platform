#!/usr/bin/env bash
# Проверка правила «никаких серых заливок» (постоянное требование владельца).
#
# Серым в интерфейсе может быть ТОЛЬКО текст, иконка, рамка (border-*/ring-*)
# и разделитель. Любая ЗАЛИВКА — фон панели, чипа, дорожки переключателя или
# тумблера, полоса прогресса, подложка под hover/нажатие — либо прозрачная
# (кольцо вместо фона), либо в акцентном тоне bg-blue-500/<8…15>.
#
# Запуск: bash scripts/no-gray.sh   (0 — чисто, 1 — есть нарушения)
set -u
cd "$(dirname "$0")/.."

# Исключения: печатный/экзаменационный рендер заданий (шапки таблиц, код-блок)
# намеренно повторяет вид бланка ФИПИ и уходит в PDF — там серый уместен.
PATTERN='bg-(gray|slate|zinc|neutral|stone)-(50|100|200|300)|bg-black/(5|10|\[0\.[0-9]+\])|bg-(gray|slate)-(400|500)/'

# Не считаем нарушением: затемнение под модалкой (bg-black/40…60) и волосяные
# разделители в 1px (w-px/h-px) — это линия, а не заливка.
hits=$(grep -rnE "$PATTERN" src --include='*.jsx' --include='*.js' \
  | grep -v 'bg-black/40\|bg-black/50\|bg-black/60' \
  | grep -v 'w-px\|h-px' || true)

if [ -n "$hits" ]; then
  echo "Серые заливки (заменить на bg-blue-500/8…15 либо на ring-1 без фона):"
  echo "$hits"
  exit 1
fi
echo "Серых заливок нет."
