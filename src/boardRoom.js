// Адрес доски (roomId). У ученика их две породы, и смешивать их нельзя:
//
//   "<id карточки>"                — доска занятия: одна на ученика, её открывают
//                                    из расписания, карточки ученика и кабинета;
//   "<id карточки>:hw:<id работы>" — доска домашней работы: своя у КАЖДОГО задания,
//                                    открывается кнопкой «Решить на доске».
//
// Раньше домашние работы ложились листами на ту же доску занятия, и к концу недели
// разбор урока, задания понедельника и задания среды лежали вперемешку одной кучей.
//
// Ключ таблицы boards — text, поэтому составной адрес хранится как есть; политики
// RLS сравнивают с карточкой ученика ПЕРВУЮ часть адреса (supabase/board_rooms.sql).
// Картинки доски по-прежнему кладутся в папку ученика (board/<id карточки>/…):
// политики storage разбирают путь по папкам, и составной адрес закрыл бы загрузку.

export const HW_ROOM = ":hw:"

// Доска занятия
export const lessonRoom = (studentId) => String(studentId)

// Доска конкретной домашней работы
export const homeworkRoom = (studentId, hwId) => `${studentId}${HW_ROOM}${hwId}`

// Карточка ученика, которой принадлежит доска (для хранилища и снимков занятий)
export const roomStudentId = (roomId) => String(roomId ?? "").split(":")[0]

// Доска домашней работы, а не занятия
export const isHomeworkRoom = (roomId) => String(roomId ?? "").includes(HW_ROOM)
