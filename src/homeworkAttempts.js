// Журнал попыток по домашней работе: что уходит в task_attempts после сдачи.
//
// Вынесено из самой сдачи (StudentDashboard) отдельной чистой функцией по двум
// причинам. Во-первых, на этих строках держится вся статистика ученика — карта
// заданий, «Где ученик ошибается», отчёт родителю, — и ошибка здесь не видна
// нигде до конца четверти. Во-вторых, только так её можно прогнать проверкой
// на выдуманных работах, не поднимая кабинет целиком.
//
// Задание попадает в журнал, когда у него есть ПРЕДМЕТ И НОМЕР экзамена. У
// собранного из банка они приезжают вместе с заданием, у нарезанного из своего
// файла — их проставляет репетитор при выдаче (поле «№» в форме). Нет номера —
// задание просто не попадает в свод по номерам; работа при этом проверяется и
// оценивается как обычно.
//
// ПРОПУСК — ЭТО НЕВЕРНО, а не отсутствие попытки. Раньше задание без ответа в
// журнал не шло вовсе, и процент считался от РЕШЁННЫХ: работа «5 из 10», где
// три задания не тронуты, давала в карте заданий 5 из 7 — 71% вместо 50%.
// Ученик, пропустивший всё, чего не знает, выглядел лучше того, кто попробовал
// и ошибся. Считаем от ОБЩЕГО числа заданий: не ответил — не решил.
//
// Исключение одно: задание БЕЗ ЭТАЛОНА (часть 2 — решение фотографией, свой
// файл без ответа). Его не проверяет и сверка, балл ему ставит репетитор
// рукой (task_attempt_mark), и записать такому пропуску «неверно» значило бы
// объявить нерешённым то, на что никто ещё не смотрел.

import { answersEqual } from "./utils"
import { taskGenKey } from "./taskTheme"

export function homeworkAttempts(hw, { answers, correct, account, token, studentId }) {
  const bank = Array.isArray(hw?.bank_tasks) ? hw.bank_tasks : []
  // Соответствие ответа заданию держится на ПОРЯДКЕ: при расхождении длин
  // попытка приписалась бы чужому номеру, а это хуже, чем её отсутствие.
  if (!bank.length || bank.length !== (correct?.length ?? -1)) return []

  // Повторная сдача — вторая попытка. Доля верных в аналитике считается по
  // первым: иначе режим «решай до верного ответа» показывал бы 50% там, где
  // тема на самом деле освоена.
  const attemptNo = Array.isArray(hw.student_answers) && hw.student_answers.length ? 2 : 1
  // Доработка присылает и принятые ответы — они уже записаны первой попыткой,
  // второй раз в журнал не идут: иначе один ответ считался бы дважды и растянул
  // бы историю по типажу.
  const kept = hw.status === "revision" && Array.isArray(hw.student_answers) ? hw.student_answers : null

  const out = []
  ;(answers || []).forEach((ans, i) => {
    const given = String(ans || "").trim()
    const task = bank[i]
    // Задание без предмета и номера (работа из файла, которой номера не
    // проставили) в журнал не идёт: свод по номерам его не примет.
    if (!task?.exam_type || task.number == null) return
    // Эталона нет — проверяет человек, а не сверка (см. шапку файла).
    if (String(correct[i] ?? "").trim() === "") return
    if (String(kept?.[i] ?? "").trim() !== "") return
    out.push({
      p_account: account,
      p_token: token,
      // Нужен id ученика У РЕПЕТИТОРА: по нему джойнит и RLS, и вся аналитика.
      p_student_id: studentId != null ? String(studentId) : null,
      p_source: "homework",
      p_source_id: hw.id,
      p_exam_type: task.exam_type,
      p_number: task.number,
      // Ключа типажа у задания из файла нет и быть не может — генератора за ним
      // не стоит. Зато бывает ТЕМА, которую поставил репетитор: она и едет
      // ключом («theme:Квадратные уравнения», см. taskTheme.js), иначе внутри
      // номера все задания были бы на одно лицо. Нет ни того, ни другого —
      // null: колонка это допускает («не из генератора»), а своды по номерам
      // такие строки считают наравне с остальными.
      p_gen_key: taskGenKey(task),
      // Пустой ответ — неверно, и сверку для этого звать незачем: она и так
      // отвечает false на пустое, но правило должно быть видно здесь, а не
      // выводиться из чужой функции.
      p_is_correct: given !== "" && answersEqual(given, correct[i]),
      p_answer: given,
      p_attempt_no: attemptNo,
    })
  })
  return out
}

// Разметка УЖЕ СДАННОЙ работы: номер, проставленный задним числом.
//
// Своя раздатка размечается когда угодно — в том числе после того, как ученик
// её сдал: репетитор нарезал файл, ученик ответил, и только на разборе дошли
// руки связать задания с номером экзамена. Сдача такую работу в журнал не
// записывала (номера у заданий тогда не было), а разметка журнала не касалась
// — и работа навсегда оставалась вне статистики: у карты заданий её как не
// было. Так на боевой потерялась работа на 44 задания: ученик ответил на 33,
// репетитор проверил и выставил балл, а в журнале по ней не было ни строки.
//
// Отсюда эта функция: по работе она говорит, как журнал ДОЛЖЕН выглядеть, а
// дальше `homework_attempts_fill` приводит его к этому виду. Считает ровно те
// же правила, что и сдача (см. выше): пропуск — неверно, задание без эталона
// в журнал не идёт, решённым считается сошедшийся ответ ИЛИ зачёт репетитора
// («Засчитать задание» — иначе разметка стёрла бы его правку сверкой).
export function markupAttempts(hw) {
  const bank = Array.isArray(hw?.bank_tasks) ? hw.bank_tasks : []
  const correct = Array.isArray(hw?.correct_answers) ? hw.correct_answers : []
  const given = Array.isArray(hw?.student_answers) ? hw.student_answers : []
  // Работа, которую ещё не сдавали, журналу ничего не должна: ответов нет, и
  // «не ответил» про неё значит «решает», а не «не решил».
  if (!given.length || !bank.length || bank.length !== correct.length) return []
  const byHand = new Set((Array.isArray(hw.credited) ? hw.credited : []).map(Number))

  const out = []
  bank.forEach((task, i) => {
    const ans = String(given[i] ?? "").trim()
    const corr = String(correct[i] ?? "").trim()
    if (!task?.exam_type || task.number == null || corr === "") return
    out.push({
      // Позиция задания, а не его номер: в раздатке по одной теме все задания
      // несут ОДИН номер, и по номеру сорок отметок легли бы в одну строку.
      task_no: i + 1,
      exam_type: task.exam_type,
      number: Number(task.number),
      gen_key: taskGenKey(task),
      correct: (ans !== "" && answersEqual(ans, corr)) || byHand.has(i + 1),
      answer: ans,
    })
  })
  return out
}
