// Понятная ошибка вместо браузерной, когда не загрузился ленивый кусок сборки.
//
// Тяжёлые куски (pdf.js, docx-preview, печать варианта, банк заданий) грузятся
// отдельными файлами по требованию, и в имени каждого стоит хэш содержимого.
// После деплоя имена другие, а страница, открытая до него, продолжает просить
// прежние. Пока сервер их отдаёт, всё в порядке; если не отдаёт — импорт падает,
// и браузер сообщает об этом невнятно: Safari говорит «Importing a module script
// failed», Chrome — «Failed to fetch dynamically imported module». Человек в этот
// момент уже выбрал файл и ждёт работы, поэтому объясняем причину словами.
//
// Сам источник беды закрыт в раскатке: куски прошлых сборок больше не стираются
// сразу (см. scripts/deploy.sh). Это — страховка на случай обрыва связи и на те
// вкладки, что провисели дольше месяца.
export async function lazyChunk(load, what) {
  try {
    return await load()
  } catch (err) {
    if (typeof navigator !== "undefined" && navigator.onLine === false) {
      throw new Error(
        `Нет связи с интернетом, поэтому ${what} не загрузился. Проверьте подключение и повторите.`,
        { cause: err }
      )
    }
    throw new Error(
      `Не удалось загрузить ${what}. Обычно это значит, что вышла новая версия сайта: обновите страницу и повторите.`,
      { cause: err }
    )
  }
}
