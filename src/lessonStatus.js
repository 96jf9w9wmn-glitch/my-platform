// Тексты уведомлений о пометке «не состоялось». Живут отдельно от модалки:
// их зовут страницы (расписание и карточка ученика), а не компонент, и
// одинаковая формулировка в обоих местах — единственный способ не рассказать
// ученику про одно и то же событие двумя разными способами.

import { LESSON_MISSED, LESSON_EXCUSED } from "./utils"
import { formatLessonWhen } from "./lessonMove"

// Что написать ученику. Пометка меняет его долг, поэтому молча её ставить
// нельзя: у ученика в кабинете цифра изменилась бы без объяснения.
export function lessonStatusNotice(status, date, time) {
  const when = formatLessonWhen(date, time)
  if (status === LESSON_MISSED) {
    return ["Занятие отмечено как пропущенное",
      `${when} — занятие не состоялось, но идёт в счёт: оплата за него начисляется как обычно.`]
  }
  if (status === LESSON_EXCUSED) {
    return ["Занятие не в счёт",
      `${when} — занятие не состоялось, оплата за него не начисляется.`]
  }
  return ["Пометка с занятия снята",
    `${when} — занятие снова считается обычным проведённым.`]
}
