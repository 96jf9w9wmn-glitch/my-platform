// Разряды в числах разделяет узкий неразрывный пробел (U+202F).
//
// toLocaleString("ru-RU") ставит между разрядами неразрывный пробел ПОЛНОЙ
// ширины: «2 000» на карточке читается как два числа подряд, а не как одно.
// Формат один на всё приложение — цена в форме ученика, долг в списке, сумма
// в квитанции и в тарифе должны выглядеть одинаково.
export const NUM_SPACE = "\u202f"

export const fmtNum = (n) => (Number(n) || 0).toLocaleString("ru-RU").replace(/\s/g, NUM_SPACE)
