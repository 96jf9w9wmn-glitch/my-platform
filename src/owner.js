// Кто видит внутренние разделы платформы.
//
// Раздел «Банк заданий» в кабинете — это просмотр генераторов (превью типажей,
// проверка вида и опечаток), инструмент владельца платформы, а не функция для
// репетиторов. Остальным аккаунтам его не должно быть видно вообще: ни пункта
// меню, ни самой страницы. Тарифы тут ни при чём — это не платная возможность,
// поэтому проверка идёт по аккаунту, а не по подписке.
//
// Репетиторы пользуются банком косвенно — через сборку вариантов, рабочие
// тетради и выдачу заданий; там доступ решает тариф (см. src/plans.js).
//
// Важно понимать границу: это скрытие интерфейса, а не защита данных. Сами
// генераторы лежат в клиентском бандле, и тот, кто откроет исходники, их
// увидит. Секретов и чужих ПДн в разделе нет, поэтому такой границы достаточно;
// если понадобится настоящая приватность — генераторы придётся уносить на
// сервер.
const OWNER_EMAILS = ["arm_227@mail.ru"]

// Раздел «Банк заданий» открыт ещё и отдельным аккаунтам — тем, кого владелец
// позвал смотреть генераторы. Список НАМЕРЕННО отдельный от OWNER_EMAILS:
// isOwner открывает вдобавок закрытые предметы (химия, биология, литература…)
// в сборке ДЗ, вариантов и на доске, а их банки не доказаны и в продуктовую
// область не входят (математика и информатика) — см. examSubjectList.js.
// Здесь только видимость раздела.
const BANK_VIEWER_EMAILS = ["leopromov222@gmail.com"]

const norm = (email) => String(email || "").trim().toLowerCase()

export function isOwner(email) {
  return OWNER_EMAILS.includes(norm(email))
}

// Видит ли аккаунт раздел «Банк заданий» (пункт меню и саму страницу).
export function canViewTaskBank(email) {
  return isOwner(email) || BANK_VIEWER_EMAILS.includes(norm(email))
}
