// Оферта объявляет прейскурант своей неотъемлемой частью (п. 1.4), но самих
// цифр в тексте юриста нет. Таблица собирается из src/plans.js — того же
// источника, из которого их берут страница «Подписка» и функции в api/. Руками
// сюда цены не вписывать: разъехавшийся с интерфейсом прейскурант — это цена,
// объявленная публично, но не та, что списывается.
function PriceList() {
  // Серые токены в тёмной теме перевёрнуты (см. index.css): dark:-варианты тут
  // дали бы тёмный текст на тёмном фоне, поэтому классы только базовые.
  const cell = "px-3 py-2 text-[13px] border-b border-gray-100"
  // Колонки тарифов не переносим: «1 990 ₽» в две строки читается как две суммы.
  // Таблица уезжает вбок внутри своего контейнера, страница при этом не едет.
  const val = `${cell} whitespace-nowrap`
  const mark = (v) => (v ? "✓" : "—")
  const limit = (v) => (v === UNLIMITED ? "без ограничений" : v === 0 ? "—" : String(v))

  return (
    <Section title="Приложение № 1. Прейскурант (тарифы и стоимость услуг)">
      <p>
        Стоимость указана в рублях Российской Федерации за один Расчётный период.
        Налог на добавленную стоимость не начисляется (п. 8.2 Договора). Те же
        сведения размещены на странице «Подписка» Сервиса.
      </p>
      <div className="overflow-x-auto -mx-1">
        <table className="min-w-full text-left text-gray-600">
          <thead>
            <tr>
              <th className={`${cell} font-semibold text-gray-800`}>Тариф</th>
              {PLANS.map((p) => (
                <th key={p.id} className={`${val} font-semibold text-gray-800`}>
                  «{p.name}»
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            <tr>
              <td className={cell}>Стоимость, месяц</td>
              {PLANS.map((p) => (
                <td key={p.id} className={val}>
                  {p.price.month === 0 ? "бесплатно" : `${fmtNum(p.price.month)} ₽`}
                </td>
              ))}
            </tr>
            <tr>
              <td className={cell}>Стоимость, 12 месяцев</td>
              {PLANS.map((p) => (
                <td key={p.id} className={val}>
                  {p.price.year === 0 ? "бесплатно" : `${fmtNum(p.price.year)} ₽`}
                </td>
              ))}
            </tr>
            {FEATURE_ROWS.map((row) => (
              <tr key={row.key}>
                <td className={cell}>{row.label}</td>
                {PLANS.map((p) => (
                  <td key={p.id} className={val}>
                    {row.kind === "always"
                      ? "✓"
                      : row.kind === "limit"
                        ? limit(p.limits[row.key]) + (p.limits[row.key] > 0 ? row.suffix || "" : "")
                        : mark(p.features[row.key])}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p>
        Состав Тарифа может изменяться в порядке п. 12.2 Договора; исключение
        прямо поименованной здесь возможности или снижение лимита признаётся
        существенным уменьшением объёма Тарифа (п. 12.3 Договора).
      </p>
    </Section>
  )
}

