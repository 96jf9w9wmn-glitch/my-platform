// Уровень (ЕГЭ / ОГЭ), к которому относится предмет.
export function levelOf(type) {
  const g = EXAM_GROUPS.find((grp) => grp.subjects.some((s) => s.type === type))
  return g ? g.key : "ОГЭ"
}

// Описание предмета по ключу генераторов.
export function subjectOf(type) {
  for (const g of EXAM_GROUPS) {
    const s = g.subjects.find((x) => x.type === type)
    if (s) return s
  }
  return null
}

// Подпись предмета целиком: «ОГЭ Математика», «ЕГЭ Математика профиль».
export function subjectLabel(type) {
  const s = subjectOf(type)
  return s ? `${levelOf(type)} ${s.label}` : type
}

// Предметы, которые доступны этому репетитору: из открытых оставляем отмеченные
// в профиле. Ничего не отмечено — открытые целиком: пустая анкета не должна
// запирать банк, репетитор просто ещё не доходил до настройки. Владельцу
// платформы отдаём весь список, включая закрытые предметы.
//
// Возвращает те же группы, что EXAM_GROUPS, только с урезанным subjects;
// пустые группы выбрасываются, чтобы в переключателе уровня не было пустого «ЕГЭ».
export function subjectGroups({ picked = null, owner = false } = {}) {
  const base = owner
    ? EXAM_GROUPS
    : EXAM_GROUPS.map((g) => ({ ...g, subjects: g.subjects.filter((s) => s.open) }))
  const known = (Array.isArray(picked) ? picked : []).filter((t) => subjectOf(t))
  if (!known.length) return base.filter((g) => g.subjects.length)
  const kept = base
    .map((g) => ({ ...g, subjects: g.subjects.filter((s) => known.includes(s.type)) }))
    .filter((g) => g.subjects.length)
  // Отмечено только то, чего этому аккаунту не видно (предмет закрыли после
  // выбора) — лучше показать открытые, чем пустой список без объяснений.
  return kept.length ? kept : base.filter((g) => g.subjects.length)
}

// Первый предмет из групп — значение по умолчанию для выбора предмета.
export function firstType(groups, fallback = "ОГЭ") {
  return groups?.[0]?.subjects?.[0]?.type || fallback
}

// Предмет из анкеты репетитора («Математика», «Физика», …) + к каким экзаменам он
// готовит → тип банка. Нужно, чтобы выбор задания открывался сразу на своём
// предмете, а не на «ОГЭ Математика» по умолчанию: репетитор ведёт один предмет и
// каждый раз выбирал его заново.
export const SUBJECT_TO_TYPE = {
  "Математика": { "ОГЭ": "ОГЭ", "ЕГЭ": "ЕГЭ Профиль" },
  "Русский язык": { "ОГЭ": "ОГЭ Русский" },
  "Английский язык": { "ОГЭ": "ОГЭ Английский" },
  "Физика": { "ОГЭ": "ОГЭ Физика" },
  "Химия": { "ОГЭ": "ОГЭ Химия" },
  "Обществознание": { "ОГЭ": "ОГЭ Обществознание" },
  "Информатика": { "ОГЭ": "ОГЭ Информатика", "ЕГЭ": "ЕГЭ Информатика" },
}

// Что предложить отметить тому, кто предметы ещё не выбирал: тип банка по анкете
// (предмет + экзамены). Проверки генераторов здесь нет намеренно — это подсказка
// в интерфейсе, а не выдача задания.
export function typesFromProfile(subject, examFocus = []) {
  const byLevel = SUBJECT_TO_TYPE[subject]
  if (!byLevel) return []
  const focus = Array.isArray(examFocus) ? examFocus : []
  // «Успеваемость» уровня банка не задаёт — берём только те, к которым готовят
  const levels = ["ОГЭ", "ЕГЭ"].filter((l) => focus.includes(l) && byLevel[l])
  return (levels.length ? levels : Object.keys(byLevel)).map((l) => byLevel[l]).filter(Boolean)
}
