// «3 ч 55 мин» — так продолжительность пишут в бланках и на сайте ФИПИ.
export function formatExamDuration(min) {
  if (!min) return ""
  const h = Math.floor(min / 60)
  const m = min % 60
  if (!h) return `${m} мин`
  return m ? `${h} ч ${m} мин` : `${h} ч`
}

// Обратный отсчёт: «3:55:04», а под час — «55:04». Часы не выравниваем нулём,
// минуты и секунды — всегда двузначные, чтобы строка не прыгала по ширине.
export function formatCountdown(ms) {
  const total = Math.max(0, Math.floor(ms / 1000))
  const h = Math.floor(total / 3600)
  const m = Math.floor((total % 3600) / 60)
  const s = total % 60
  const mm = String(m).padStart(2, "0")
  const ss = String(s).padStart(2, "0")
  return h ? `${h}:${mm}:${ss}` : `${mm}:${ss}`
}
