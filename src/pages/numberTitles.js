// Подпись номера. themes — то, что вернул taskThemes(examType, number):
// когда названия раздела нет в таблице, его заменяют собственные темы
// генераторов — это честно (так номер и устроен у нас) и всегда точно.
export function numberTitle(examType, number, themes) {
  const known = NUMBER_TITLES[examType]?.[number]
  if (known) return known
  const names = (themes || []).map((t) => t.theme).filter(Boolean)
  if (!names.length) return `Задание ${number}`
  if (names.length <= 2) return names.join(" · ")
  return names.slice(0, 2).join(" · ") + " …"
}
