// Лёгкие константы банка заданий: сколько номеров в части 1 и какие номера входят
// в часть 2. Вынесены из taskBankApi.js отдельным файлом намеренно: сам taskBankApi
// тянет все генераторы (~3,3 МБ), а эти два объекта нужны странице «Варианты» уже
// при первой отрисовке. Импортировать ради них taskBankApi — значит грузить весь
// банк ещё до того, как пользователь нажал «Собрать вариант».
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i)

// Номера части 1, из которых собирается вариант. Список, а не «сколько»: в
// информатике номера идут не подряд.
//
// Информатика: в вариант берём только то, что решается на бумаге. У ОГЭ это
// ровно часть 1 (№1–10) — №11–16 сдают за компьютером (архив с файлами,
// таблица, презентация, программа), и на печатном листе они нерешаемы. У КЕГЭ
// по той же причине выпадают №3, 9, 10, 17, 18, 22, 24, 26, 27 (таблица или
// текстовый файл к заданию) и №25 (ответ — перечень из десятков чисел).
// Возвращать их сюда можно только вместе с выдачей файлов ученику.
//
// Базовый ЕГЭ идёт целиком: части 2 у него нет, все 21 задание — с коротким
// ответом и решаются на листе. До 28.08.2026 здесь стояло range(1, 12): база
// унаследовала список профиля, где 12 — это длина ЧАСТИ 1, и вариант молча
// выходил вдвое короче настоящего КИМ.
//
// Профиль — по нумерации КИМ-2027 (часть 1 настоящего экзамена — №1–13). Из
// варианта пока выпадают: №6 (случайная величина — новое задание 2027 года,
// генераторов и пула ФИПИ ещё нет) и №13 (экономическая задача, переехавшая из
// части 2: ответы её генераторов пока в формате развёрнутого решения —
// «259 200 рублей», «n = 3, m = 5» — и сверку краткого ответа не проходят;
// вернуть №13 сюда можно только вместе с переводом ответов на числовой формат).
export const VARIANT_PART1 = {
  "ОГЭ": range(1, 19),
  "ЕГЭ": range(1, 21),
  "ЕГЭ Профиль": [...range(1, 5), ...range(7, 12)],
  "ОГЭ Информатика": range(1, 10),
  "ЕГЭ Информатика": [1, 2, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 19, 20, 21, 23],
}

// Типы экзаменов, из которых вообще можно собрать вариант.
export const VARIANT_TYPES = Object.keys(VARIANT_PART1)

export const part1NumbersOf = (examType) => VARIANT_PART1[examType] || VARIANT_PART1["ОГЭ"]

// Длина массива ответов части 1: ответы лежат по индексу «номер − 1», поэтому
// массив длиной с САМЫЙ БОЛЬШОЙ номер, а не с их количество (в информатике это
// разные числа).
export const part1SlotsOf = (examType) => {
  const nums = part1NumbersOf(examType)
  return nums[nums.length - 1]
}

// Сколько номеров в части 1 — знаменатель балла.
export const part1CountOf = (examType) => part1NumbersOf(examType).length

// Номера части 2, входящие в собранный вариант (развёрнутое решение: фото и
// балл от репетитора). У ЕГЭ Профиль (нумерация КИМ-2027) это 14, 16, 19, 20 —
// пропуски не случайны: генераторов №15 (стереометрия с доказательством),
// №17 (прикладное моделирование — новое задание 2027 года) и №18 (планиметрия
// с доказательством) в банке пока нет, и поставить их в список значит показать
// репетитору «нет в банке» при каждой сборке.
export const PART2_NUMBERS = { "ОГЭ": [20, 21, 22, 23, 24, 25], "ЕГЭ Профиль": [14, 16, 19, 20] }

export const part2NumbersOf = (examType) => PART2_NUMBERS[examType] || []

// Подпись списка номеров: «№14» / «20–25» / «14, 16, 19–20». Диапазоном
// пишем только подряд идущие: у части 2 профиля есть пропуски, и «14–20»
// пообещало бы ученику задания, которых в варианте нет. hash: false — там, где
// «№» уже стоит во фразе («для выполнения заданий 14, 16, 19–20»).
export function numbersLabel(nums, { hash = true } = {}) {
  const list = [...new Set(nums)].sort((a, b) => a - b)
  if (!list.length) return ""
  if (list.length === 1) return hash ? `№${list[0]}` : `${list[0]}`
  const runs = []
  for (const n of list) {
    const last = runs[runs.length - 1]
    if (last && n === last[1] + 1) last[1] = n
    else runs.push([n, n])
  }
  return runs.map(([a, b]) => (a === b ? `${a}` : `${a}–${b}`)).join(", ")
}

// Задание относится ко второй части (развёрнутый ответ + фото решения).
// Сравнивать «номер больше N» нельзя: в информатике части 2 нет вовсе, а номера
// доходят до 23.
export const isPart2Number = (examType, number) => part2NumbersOf(examType).includes(number)

// Уровень экзамена по типу банка — им отбираются ученики с подходящей целью.
export const examLevelOf = (examType) => (String(examType).startsWith("ЕГЭ") ? "ЕГЭ" : "ОГЭ")

// Типы экзаменов, у которых задания 1–5 идут связанным практическим модулем
// (общий текст и рисунок на пять номеров), и длина такого модуля. Список
// продублирован из MODULES в taskModules.js, чтобы страница «Варианты» могла
// подписать кнопку «Заменить блок 1–5» не загружая сами модули; расхождение
// ловит проверка в taskBankApi.js при разработке.
export const MODULE_EXAM_TYPES = ["ОГЭ"]
export const MODULE_COUNT = 5

// Номер входит в практический модуль №1–5 (когда для типа экзамена есть модули).
export function isModuleNumber(examType, number) {
  return MODULE_EXAM_TYPES.includes(examType) && number >= 1 && number <= MODULE_COUNT
}
