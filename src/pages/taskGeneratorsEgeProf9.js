// Подбор (c, u, v, f₀, f₁) для f=f₀(c+u)/(c−v): частота приёмника обязана быть целой.
function dopplerParams() {
  for (let g = 0; g < 400; g++) {
    const c = pick([300, 320, 330, 340, 350, 360])
    const u = randInt(2, 18)
    const v = randInt(2, 18)
    // f₀ обязана делиться на знаменатель несократимой дроби (c+u)/(c−v) — тогда f₁ целая
    const gg = gcd(c + u, c - v)
    const p = (c + u) / gg, q = (c - v) / gg
    const n = randInt(1, 400)
    const f0 = q * n, f1 = p * n
    if (f0 >= 100 && f0 <= 400 && f1 - f0 >= 5 && f1 - f0 <= 40) return { c, u, v, f0, f1 }
  }
  return { c: 340, u: 2, v: 17, f0: 170, f1: 180 }
}

