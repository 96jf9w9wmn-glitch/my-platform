// Дробь-коэффициент: 0,8 → 4/5 (несократимая, для показа столбиком).
function fracOf(x, maxDen = 1000) {
  for (let d = 1; d <= maxDen; d++) {
    const n = x * d
    if (Math.abs(n - Math.round(n)) < 1e-9) { const g = gcd(Math.round(n), d); return [Math.round(n) / g, d / g] }
  }
  return [x, 1]
}
// Согласование «километр» с числом: 21 километр, 64 километра, 96 километров, 5,6 километра.
function kmWord(x) {
  if (!Number.isInteger(x)) return "километра"
  const a = Math.abs(x) % 100, b = a % 10
  if (a > 10 && a < 20) return "километров"
  if (b === 1) return "километр"
  if (b >= 2 && b <= 4) return "километра"
  return "километров"
}
