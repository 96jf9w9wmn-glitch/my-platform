// Число в виде «m·10ᵉ» (мантисса — короткая десятичная).
function sci(mant, e) { return `${ru(mant)}·10${sup(e)}` }
const TIMES = { 2: "вдвое", 3: "втрое", 4: "вчетверо" }
const timesUp = (n) => (TIMES[n] ? TIMES[n] : `в ${n} раз`)
// «в 2 раза» / «в 8 раз»
const timesWord = (n) => (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? "раза" : "раз")
// «2 моля» / «5 молей» / «1 моль»
const moleWord = (n) => (n === 1 ? "моль" : n >= 2 && n <= 4 ? "моля" : "молей")

