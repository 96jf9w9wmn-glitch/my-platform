const randInt = (min, max) => min + Math.floor(Math.random() * (max - min + 1))
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)]
const clean = (x) => Math.round(x * 1e9) / 1e9

// Число «по-русски»: десятичная запятая, минус — U+2212.
function ru(x) {
  if (typeof x !== "number") return String(x)
  const s = Number.isInteger(x) ? String(x) : String(clean(x))
  return s.replace(".", ",").replace(/^-/, "−")
}
// Дробь столбиком (см. renderTaskMath в src/utils.js).
const fT = (n, d) => `⟦f:${n}:${d}⟧`

// ── Типаж 1. Максимальная тепловая мощность ────────────────────────────────
// P(R) = ε²R/(r+R)², P'(R) = ε²(r − R)/(r + R)³, максимум при R = r и равен
// ε²/(4r). Пары (ε, r) отобраны так, чтобы это число было целым: ε² должно
// делиться на 4r. Демонстрационная пара (50; 1) → 625 в наборе первая.
const EMF_PAIRS = (() => {
  const out = []
  for (const r of [1, 2, 4, 5]) {
    for (let e = 30; e <= 120; e += 10) {
      const P = (e * e) / (4 * r)
      if (!Number.isInteger(P) || P < 100 || P > 4000) continue
      out.push([e, r, P])
    }
  }
  return out
})()

function t17ModHeatPower() {
  const [emf, r, P] = pick(EMF_PAIRS)
  return {
    condition_text:
      `На заводе имеется генератор с ЭДС ε = ${emf} В и внутренним сопротивлением ` +
      `r = ${r} Ом. Инженер подключает к генератору нагрузку, используя реостат, чтобы ` +
      `установить сопротивление нагрузки R (в омах). Сила тока в цепи (в амперах) ` +
      `определяется законом Ома: I = ${fT("ε", "r + R")}. Тепловая мощность (в ваттах), ` +
      `выделяемая в нагрузке, может быть рассчитана по формуле Джоуля — Ленца: P = I²R. ` +
      `Какова максимальная тепловая мощность P, которая может быть выделена нагрузкой?`,
    answer: `${P} Вт`,
    solution:
      `Выразим тепловую мощность через ЭДС и сопротивление: P = ${fT("ε²R", "(r + R)²")}. ` +
      `Подставив ε = ${emf} и r = ${r}, получим функцию P(R) = ${fT(`${emf * emf}R`, `(R + ${r})²`)}. ` +
      `Её производная равна P′(R) = ${fT(`${emf * emf}(${r} − R)`, `(R + ${r})³`)}. Сопротивление ` +
      `нагрузки не может быть отрицательным, поэтому рассматриваем R ≥ 0. Производная ` +
      `положительна при 0 ≤ R < ${r} и отрицательна при R > ${r}, значит функция P(R) ` +
      `возрастает на отрезке [0; ${r}] и убывает на луче [${r}; +∞) и достигает наибольшего ` +
      `значения в точке ${r}. Таким образом, наибольшая тепловая мощность равна ` +
      `P(${r}) = ${fT(`${emf * emf} · ${r}`, `(${r} + ${r})²`)} = ${P} Вт.`,
    // Независимая проверка (verify17mod.mjs): максимум P(R) ищется численно по
    // сетке, формула берётся ровно в том виде, как напечатана в условии.
    verify: { kind: "max", f: (R) => (emf * emf * R) / ((r + R) * (r + R)), dom: [0, 40 * r], ans: P },
  }
}

// ── Типаж 2. Амплитуда вынужденных колебаний корабля ───────────────────────
// A = kθ₀·τ²/√((T² − τ²)² + nτ²T²). При x = τ² исследуется
// f(x) = x²/(x² + (n − 2)T²x + T⁴); f′(x) = 0 даёт x₀ = T²/(1 − n/2), то есть
// τ = T/√(1 − n/2).
//
// Обозначим s = √(1 − n/2). Тогда ответ τ = T/s, и чтобы он был целым, параметры
// задаются ЧЕРЕЗ s: n = 2(1 − s²), T = s·τ. Демонстрационный набор — s = 0,98:
// n = 0,0792, τ = 15, T = 14,7. Значения s взяты так, чтобы и n, и T печатались
// короткими десятичными дробями, а n оставалось малым (это коэффициент
// сопротивления воды).
const WAVE_S = [0.98, 0.96, 0.95, 0.94, 0.92, 0.9]
const WAVE_TAU = [10, 12, 15, 20, 25, 30]
const WAVE_K = [0.85, 0.88, 0.9, 0.91, 0.93, 0.95]

function t17ModShipAmplitude() {
  const s = pick(WAVE_S)
  const tau = pick(WAVE_TAU)
  const T = clean(s * tau)
  // Период свободных качаний печатается на бланке — он должен быть короткой
  // десятичной дробью, иначе условие выглядит как результат округления.
  if (Math.abs(T * 10 - Math.round(T * 10)) > 1e-9) return null
  const n = clean(2 * (1 - s * s))
  const k = pick(WAVE_K)
  const th = randInt(7, 11)

  const A = (t) => k * th * (t * t) / Math.sqrt((T * T - t * t) ** 2 + n * t * t * T * T)
  return {
    condition_text:
      `Амплитуда вынужденных колебаний корабля при качке на волнении выражается формулой ` +
      `A = ${ru(k)}θ₀ · ${fT("τ²", "√{(T² − τ²)² + nτ²T²}")}, где k = ${ru(k)} — коэффициент, ` +
      `зависящий от отношения ширины корабля к длине волны, θ₀ = ${th}° — угол наибольшего ` +
      `волнового склона, τ — период волны (в секундах), T = ${ru(T)} с — период свободных ` +
      `качаний корабля на тихой воде, n = ${ru(n)} — коэффициент, зависящий от величины ` +
      `сопротивления воды. При каком периоде волны амплитуда вынужденных колебаний корабля ` +
      `будет наибольшей? Ответ дайте в секундах.`,
    answer: String(tau),
    solution:
      `Так как A > 0, максимумы A и A² достигаются в одной точке. Положим x = τ², x > 0. ` +
      `Достаточно исследовать на экстремум функцию A² = (kθ₀)²f(x), где ` +
      `f(x) = ${fT("x²", "x² + (n − 2)T²x + T⁴")}. Знаменатель при x > 0 положителен. ` +
      `Производная равна f′(x) = ${fT("T²x(2T² − (2 − n)x)", "(x² + (n − 2)T²x + T⁴)²")}. ` +
      `В области определения множители T²x и знаменатель положительны, поэтому f′(x) = 0 ` +
      `при 2T² − (2 − n)x = 0, то есть x₀ = ${fT("T²", "1 − n/2")}. При 0 < x < x₀ производная ` +
      `положительна, при x > x₀ — отрицательна, значит x₀ — точка максимума. Следовательно, ` +
      `τ = ${fT("T", "√{1 − n/2}")} = ${fT(ru(T), `√{1 − ${ru(n)}/2}`)} = ` +
      `${fT(ru(T), ru(s))} = ${tau}.`,
    // Проверка численная: argmax A(τ) на сетке (verify17mod.mjs).
    verify: { kind: "argmax", f: A, dom: [0.5, 4 * tau], ans: tau },
  }
}

