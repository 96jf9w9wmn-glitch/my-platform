//
// ЭТАЛОН — только демонстрационный вариант ФИПИ 2027 (проект, подготовлен 21.08.2026):
// ~/Desktop/ФИПИ/ЕГЭ Математика профиль/Демо 2027 (проект)/ДЕМО профиль 2027.pdf, с. 7.
// Открытого банка ФИПИ по этому номеру НЕ существует: задание новое, в tasks.json
// его нет. Поэтому здесь ОДИН типаж — ровно тот, что напечатан в демоверсии:
//
//   «Организаторы лотереи выпустили 10 000 билетов. Выигрыши распределены следующим
//    образом. [таблица «Выигрыш (в рублях)» / «Число выигрышных билетов»]
//    Найдите математическое ожидание величины "выигрыш на один билет".
//    Ответ дайте в рублях.»   Ответ: 55.
//
// Демоверсия прямо предупреждает, что примеры «не исчерпывают всего многообразия
// возможных формулировок», так что другие типажи №6 (дисперсия, распределение
// числа успехов, ряд распределения) сюда ещё предстоит добавить — но выдумывать их
// без эталона нельзя, и заявлять номер закрытым тоже.
//
// ЧИСЛА: тираж, выигрыши и число крупных призов берутся из круглых наборов, а
// число самых мелких выигрышей ПЕРЕБИРАЕТСЯ — оставляются только те значения,
// при которых ожидание выходит целым и правдоподобным. Округлять ответ нельзя:
// в бланк идёт точное число рублей.

import { tableBlock } from "../utils.js"

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)]

const NBSP = " "
// Разряды неразрывным пробелом: в КИМ напечатано «10 000», а не «10000».
const grp = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, NBSP)

// Согласование «билет» с числом.
const ticketWord = (n) => {
  const a = Math.abs(n) % 100, b = a % 10
  if (a > 10 && a < 20) return "билетов"
  if (b === 1) return "билет"
  if (b >= 2 && b <= 4) return "билета"
  return "билетов"
}

// ── условие делимости ──────────────────────────────────────────────────────
// Мелкий выигрыш всегда 100 ₽, все остальные — кратны 1000, тираж кратен 1000,
// ожидание E целое. Тогда число мелких билетов
//     c₀ = (E·N − Σ pᵢcᵢ) / 100
// не только целое, но и КРУГЛОЕ (кратно 10): и E·N, и сумма по крупным выигрышам
// кратны 1000. Без этого таблица получалась бы с числами вида 1137 — в КИМ таких
// не бывает.
const SMALL_PRIZE = 100
const ROUND_STEP = 10

// Тиражи и «лестницы» выигрышей: первая — ровно из демоверсии.
const RUNS = [5000, 10000, 20000, 25000, 50000]
const LADDERS = [
  [1000, 5000, 10000, 50000],
  [1000, 2000, 10000, 100000],
  [1000, 5000, 20000, 100000],
  [2000, 5000, 25000, 50000],
  [1000, 10000, 25000, 50000],
]
// Числа билетов по крупным выигрышам — круглые и убывающие, как в КИМ.
const COUNTS = [
  [50, 100, 150, 200, 250, 300],
  [20, 25, 40, 50, 60, 100],
  [5, 10, 15, 20, 25],
  [1, 2, 3, 5],
]
// Правдоподобный размах ожидаемого выигрыша на билет (в демоверсии — 55 ₽).
const E_MIN = 20
const E_MAX = 150

// Математическое ожидание выигрыша на один билет по таблице распределения.
function t06rvLotteryExpect() {
  const N = pick(RUNS)
  const prizes = pick(LADDERS)
  const big = COUNTS.map((pool) => pick(pool))
  // Чем крупнее выигрыш, тем реже он встречается: в КИМ числа билетов строго
  // убывают, и одинаковые соседи («20 и 20») выдали бы сгенерированную таблицу.
  if (big.some((c, i) => i && c >= big[i - 1])) return null
  const S = prizes.reduce((acc, p, i) => acc + p * big[i], 0)
  const bigTotal = big.reduce((a, b) => a + b, 0)

  // Число мелких билетов НЕ подбирается наугад: перебираем все круглые значения
  // и оставляем те, при которых ожидание (S + 100·c₀)/N выходит целым и
  // правдоподобным. Наугад отсеивалось бы 9 наборов из 10 — а generateTask даёт
  // типажу всего 40 попыток.
  const fit = []
  for (let c0 = big[0] + ROUND_STEP; c0 <= 2000; c0 += ROUND_STEP) {
    // Мелких билетов должно быть больше всех остальных, а выигрышных — заметно
    // меньше тиража: иначе таблица перестаёт быть похожей на лотерейную.
    if (c0 + bigTotal > N / 4) break
    const T = S + SMALL_PRIZE * c0
    if (T % N !== 0) continue
    const E = T / N
    if (E < E_MIN || E > E_MAX) continue
    fit.push([c0, E])
  }
  if (!fit.length) return null
  const [c0, E] = pick(fit)

  const row = [SMALL_PRIZE, ...prizes]
  const cnt = [c0, ...big]
  return {
    condition_text:
      `Организаторы лотереи выпустили ${grp(N)} ${ticketWord(N)}. ` +
      `Выигрыши распределены следующим образом.\n` +
      tableBlock([
        ["Выигрыш (в рублях)", ...row.map(grp)],
        ["Число выигрышных билетов", ...cnt.map(grp)],
      ]) +
      `\nНайдите математическое ожидание величины «выигрыш на один билет». ` +
      `Ответ дайте в рублях.`,
    answer: String(E),
    // Независимая проверка (fipi_bank_ege_prof/verify06_17.mjs) читает таблицу из
    // САМОГО условия и считает Σpᵢcᵢ/N заново — эти числа она не видит.
    verify: { kind: "expect", N, prizes: row, counts: cnt, ans: E },
  }
}

