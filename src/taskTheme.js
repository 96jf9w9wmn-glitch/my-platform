// Тема задания, привязанная рукой репетитора.
//
// У задания из банка тема известна сама: за ним стоит генератор, ключ типажа
// едет в задании (gen_key), а подпись темы лежит рядом с ним в самом банке. У
// задания, нарезанного из своего файла, генератора нет и взяться теме неоткуда
// — её пишет репетитор: выбирает из тем этого номера или заводит свою.
//
// Хранится она двумя полями, и второе — то же самое, сказанное журналу попыток:
//   * homework.bank_tasks[i].theme — подпись темы в самой работе;
//   * task_attempts.gen_key = "theme:<подпись>" — она же в журнале.
//
// Своей колонки под тему в журнале нет НАМЕРЕННО. gen_key — это и есть «чем
// задание отличается внутри номера»: по нему считают «Где ученик ошибается»,
// сводку в «Результатах» и темы отчёта родителю. Заведи рядом вторую колонку —
// и у одного ученика по одному номеру появились бы две разные разбивки, а
// собранное из банка и нарезанное из файла перестали бы складываться в одну
// тему (в отчёте они складываются: там строки группируются по ПОДПИСИ темы).
const PREFIX = "theme:"

// Подпись темы, как она уходит в работу: без краёв, без двойных пробелов и не
// длиннее строки, которую можно прочитать в списке.
export function normalizeTheme(value) {
  const s = String(value ?? "").replace(/\s+/g, " ").trim().slice(0, 80)
  return s || null
}

// Тема → ключ журнала. Пустая тема ключа не даёт: строка попытки уйдёт с
// gen_key = null, как и раньше, и посчитается по номеру.
export const themeGenKey = (theme) => {
  const s = normalizeTheme(theme)
  return s ? PREFIX + s : null
}

// Ключ журнала → тема, если это тема репетитора. Для ключа типажа — null:
// подпись такому ключу даёт банк (см. typeLabels).
export const themeFromKey = (key) =>
  typeof key === "string" && key.startsWith(PREFIX) ? key.slice(PREFIX.length) : null

// Ключ для журнала попыток по самому заданию работы. Типаж банка идёт первым:
// он точнее темы и по нему задание воспроизводится свежими числами.
export const taskGenKey = (task) => task?.gen_key || themeGenKey(task?.theme)
