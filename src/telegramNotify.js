// Сообщить серверу, что произошло событие, о котором стоит написать репетитору
// в Telegram (api/telegram.js → ?action=notify).
//
// Почему это делает клиент, а не база: сдача ДЗ, работа по варианту и сообщение
// в чате пишутся напрямую из браузера ученика (так устроен RLS), и серверу
// неоткуда узнать о них самому — триггеров с исходящей сетью на базе нет.
//
// Клиент сообщает ТОЛЬКО тип события и его id. Что именно случилось, кому это
// принадлежит и стоит ли вообще писать — сервер проверяет в базе сам, поэтому
// подделать уведомление этим вызовом нельзя.
//
// Вызов намеренно «выстрелил и забыл»: если бот не настроен, репетитор его не
// подключил или сеть отвалилась — ученик не должен видеть ни ошибки, ни задержки.

export function notifyTutor(kind, id) {
  if (!kind || id == null) return
  try {
    fetch("/api/telegram?action=notify", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ kind, id }),
      keepalive: true,      // переживает переход на другую страницу сразу после сдачи
    }).catch(() => {})
  } catch {
    // Уведомление — вежливость, а не часть сдачи работы.
  }
}
