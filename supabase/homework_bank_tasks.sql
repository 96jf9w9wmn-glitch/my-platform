-- Домашняя работа из банка заданий: чертежи, файлы и программы
-- ============================================================
--
-- ЗАЧЕМ. До этой миграции домашняя работа хранила условия ОДНОЙ строкой текста
-- (homework.description), и в сборку из банка шли только самодостаточные
-- задания — без чертежа, архива, таблицы, программы и общего текста для чтения.
-- Из-за этого у ОГЭ Информатики из 16 номеров были недоступны 10, у ЕГЭ
-- Информатики — 10 из 27, у математики — вся геометрия. Репетитор видел
-- бледные номера и не понимал, почему они «не работают».
--
-- Колонка bank_tasks хранит собранные задания как есть: условие, ответ, ключ
-- типажа и всё приложенное. Чертежи приходят из генераторов как data-URI
-- (SVG внутри самой строки), файлы .zip/.xlsx/.txt — как данные, из которых
-- кабинет ученика собирает файл на лету. Поэтому ничего не грузится в Storage
-- и подписывать ссылки не нужно: задание самодостаточно внутри строки.
--
-- ЧТО ОСТАЁТСЯ ПО-СТАРОМУ. description по-прежнему хранит текст условий
-- («1. …», «2. …») и остаётся источником для списка работ, телеграм-бота и
-- старых записей. bank_tasks — дополнение к нему, а не замена: строка без
-- bank_tasks (работа своим файлом, сборка ИИ, всё выданное раньше)
-- показывается ровно как раньше.
--
-- ПРАВА. grant на homework выдан таблично (rls_step3_policies.sql:
-- `grant select, update on public.homework to app_user`), поэтому новая
-- колонка читается учеником сразу — доступ решают те же политики
-- homework_read_own / homework_submit. Поимённых грантов на этой таблице нет,
-- добавлять ничего не нужно.
--
-- Выполнить в SQL Editor (https://db.precettore.ru/ → SQL Editor).

alter table public.homework add column if not exists bank_tasks jsonb;

comment on column public.homework.bank_tasks is
  'Задания, собранные из банка: [{number, condition_text, condition_tail, answer, gen_key, image_url, program, archive, spreadsheet, textFile, source_text, source_title}]. Дополняет description (там те же условия текстом), нужно ради чертежей и прилагаемых файлов. null — работа собрана не из банка.';
