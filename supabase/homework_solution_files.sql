-- Фото решения — к каждому заданию домашней работы отдельно
-- ========================================================
--
-- ЗАЧЕМ. Раньше ученик решал работу так: сверху список заданий, а поля ввода —
-- одной сеткой в самом низу, и одно-единственное фото решения на всю работу.
-- Чтобы вписать ответ к третьему заданию, приходилось прокручивать страницу
-- вниз и считать номера, а фотография была одна на десять задач.
--
-- Теперь задание, поле ответа и кнопка фото стоят рядом: решил — сразу вписал
-- и сразу сфотографировал. Для этого нужна не одна ссылка (submission_url), а
-- карта «номер задания → файл».
--
-- ЧТО ОСТАЁТСЯ ПО-СТАРОМУ. submission_url никуда не делся: в него по-прежнему
-- уходит первое фото, поэтому старая карточка «Решение ученика» у репетитора и
-- в кабинете родителя работает как работала. Работа без solution_files
-- (выданная и сданная раньше) показывается ровно как раньше.
--
-- ПРАВА. grant на homework выдан таблично (rls_step3_policies.sql:
-- `grant select, update on public.homework to app_user`), поэтому новая колонка
-- читается и пишется учеником сразу — доступ решают те же политики
-- homework_read_own / homework_submit. Поимённых грантов тут нет.
--
-- Файлы лежат в приватном бакете homework (storage_private.sql), ссылки
-- подписываются на клиенте (src/storageUrl.js): signRows понимает и объект,
-- поэтому карта подписывается тем же местом, что и одиночные поля.
--
-- Выполнить в SQL Editor (https://db.precettore.ru/ → SQL Editor).

alter table public.homework add column if not exists solution_files jsonb;

comment on column public.homework.solution_files is
  'Фото решения по заданиям работы: {"1": "<url>", "2": "<url>"} — ключ это номер задания в работе. Дополняет submission_url (там первое из этих фото). null — работа сдана до появления колонки или решение не требовалось.';

-- Кэш схемы PostgREST: pgrst_ddl_watch делает это сам, строка нужна для
-- случая, когда миграцию гоняют там, где событийного триггера нет.
NOTIFY pgrst, 'reload schema';
