-- Тема БЕЗ номера экзамена: статистика для ученика, который к экзамену не готовится.
--
-- Выполнить в Studio → SQL Editor. Идемпотентно.
--
-- Журнал попыток был устроен экзаменом: строка писалась только по паре
-- «предмет + НОМЕР задания на экзамене», и колонка number стояла NOT NULL. Для
-- выпускника это верно, но платформой пользуются и там, где никакого экзамена
-- нет — семиклассник, подтягивающий успеваемость. У его заданий номера нет и
-- быть не может, поэтому в журнал не попадало НИ ОДНО из них: карта заданий,
-- «Где ученик ошибается» и темы отчёта родителю у такого ученика оставались
-- пустыми навсегда, и сказать ему, над чем работать, платформа не могла вовсе.
--
-- Теперь номер необязателен, а разбивку внутри предмета держит ТЕМА — тот же
-- gen_key = "theme:<подпись>" (src/taskTheme.js), которым размечают задание из
-- своего файла. Второй колонки под тему по-прежнему нет и заводить нельзя: у
-- одного ученика появились бы две разные разбивки.
--
-- ЧТО ЭТО МЕНЯЕТ В ЧТЕНИИ: строка без номера не попадает в карту заданий (она
-- про номера экзамена) и считается только по теме. Все своды по номеру
-- обязаны такие строки ПРОПУСКАТЬ, а не показывать «задание №null»:
-- TaskMap.jsx, WeakTypes.jsx, StudentResults.jsx это уже делают.
--
-- Сигнатуры функций НЕ меняются: p_number у task_attempt_log и
-- task_attempt_mark и так smallint, а null в него не пускала ровно эта
-- проверка колонки. homework_attempts_fill получает номер из jsonb
-- ((x->>'number')::smallint), и отсутствующее поле там само даёт NULL.
ALTER TABLE public.task_attempts ALTER COLUMN number DROP NOT NULL;

