-- Файлы в методичке репетитора.
--
-- Методичка задумывалась текстом, но материал к номеру редко живёт одним
-- текстом: у репетитора к заданию лежит своя памятка PDF, скрин разбора,
-- таблица формул. Держать их отдельно от методички — значит искать их во время
-- занятия по всему компьютеру, ради чего методичка и заводилась.
--
-- Файлы лежат СПИСКОМ в самой строке: { name, url, size, type }. Отдельная
-- таблица тут дала бы строку на файл и join ради двух-трёх вложений, а сами
-- файлы всё равно живут не в базе, а в хранилище.
--
-- Хранилище — приватный бакет `homework`, каталог `<tutor_id>/task-notes/…`:
-- политика «tutor own files» (supabase/storage_private.sql) уже пускает
-- репетитора в его собственный каталог, поэтому политики трогать не нужно.
-- Ученик методичек не видит вовсе — это материал репетитора, а не задание.

alter table public.task_notes
  add column if not exists files jsonb not null default '[]'::jsonb;

notify pgrst, 'reload schema';
