-- Часовые пояса: расписание перестаёт зависеть от того, где находится
-- репетитор.
--
-- Занятие лежит настенным временем («2026-09-10», «18:00») внутри
-- students.lessons, без пояса. Пока обе стороны жили в одном поясе, это было
-- верно; после переезда репетитора в Армению (UTC+4) одно и то же «18:00»
-- стало означать разные моменты у него и у ученика в Москве.
--
-- Пояс нигде не выбирается руками: устройство и так знает, в какой стране оно
-- находится. Каждая сторона записывает свой пояс сама, а у расписания
-- появляется ЯКОРЬ — пояс, в котором время записано и в котором его видит
-- ученик. Якорь не двигается при переезде репетитора, поэтому у ученика,
-- родителя, в квитанции и в уведомлении время остаётся прежним; меняется
-- только показ в кабинете самого репетитора (см. src/timezone.js).
--
-- ВЫПОЛНЕНА на боевой 06.09.2026.
--
-- Пока миграция не выполнена, колонок нет: клиент отбрасывает их при
-- сохранении и работает ровно как раньше — время везде одно и то же.

begin;

-- Якорь расписания: пояс, в котором записано время занятий этой карточки.
-- Заполняется САМ, когда ученик впервые заходит в кабинет со своего
-- устройства; до этого пусто и перевода нет.
alter table public.students add column if not exists timezone text;

-- Пояс устройства ученика. Пишет его кабинет ученика при каждом заходе:
-- по нему заполняется якорь, и по нему репетитор понимает, что ученик уехал.
alter table public.student_accounts add column if not exists timezone text;

-- Пояс устройства репетитора. Нужен не кабинету (там он берётся с устройства),
-- а тем, кто пишет репетитору со стороны: кабинету ученика, когда он
-- составляет текст уведомления о переносе.
alter table public.tutors add column if not exists timezone text;

-- Гранты. У student_accounts табличный SELECT снят ещё в rls_step1_secrets.sql
-- (иначе аноним читал бы password_hash), и права выданы поимённо — новая
-- колонка без явного гранта была бы невидима, а запрос кабинета отдавал бы
-- 42501 целиком.
grant select (timezone) on public.student_accounts to anon, authenticated, app_user;
grant update (timezone) on public.student_accounts to anon, authenticated, app_user;

commit;

