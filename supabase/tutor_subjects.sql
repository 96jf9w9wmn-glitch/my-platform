-- Предметы, которые ведёт репетитор: выполнить один раз в SQL Editor нашей базы.
--
-- Зачем колонка, а не вывод из анкеты: анкета спрашивает ОДИН предмет словом
-- («Математика») и экзамены отдельно, а банк заданий устроен по типам
-- («ОГЭ Математика», «ЕГЭ Профиль», «ЕГЭ Информатика»). Репетитор часто ведёт
-- несколько типов сразу, и вывести их из анкеты нельзя — приходилось каждый раз
-- выбирать предмет заново при сборке ДЗ и вставке задания на доску.
--
-- Значения — ключи генераторов из src/pages/examSubjectList.js (поле type).
-- NULL и пустой массив значат «не выбирал»: интерфейс тогда показывает все
-- открытые предметы, а не запирает банк.
alter table public.tutors
  add column if not exists bank_subjects text[];

-- ВАЖНО: после rls_step3_policies.sql табличного SELECT на tutors нет — права
-- выданы поимённо по колонкам. Без этого гранта `select *` в App.jsx перестанет
-- отдавать профиль целиком (42501), и репетитор не войдёт в кабинет.
-- Ученику и родителю колонка не нужна: они карточку репетитора только читают.
grant select (bank_subjects) on public.tutors to authenticated;
