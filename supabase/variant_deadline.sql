-- Срок сдачи варианта (06.09.2026).
--
-- У домашней работы срок был с самого начала (homework.deadline), а у варианта
-- его не было вовсе: время у варианта мыслилось продолжительностью самого
-- экзамена (235 минут с нажатия «Начать»), и это разные вещи — «сколько идёт
-- работа» и «до какого числа её сдать». Из-за этого пробник, выданный за две
-- недели до экзамена, ничем не отличался от выданного вчера: ни у репетитора в
-- списке, ни у ученика в кабинете не было даты, к которой его ждут.
--
-- Срок стоит на САМОМ варианте, а не на выдаче ученику: вариант выдаётся всем
-- сразу одной строкой, и «пробник до воскресенья» — это одно решение на всех.
-- Разные сроки разным ученикам потребовали бы колонки в variant_submissions и
-- второго места, где срок правят; понадобится — добавим тогда.
--
-- Колонка nullable: у всех выданных до этой миграции вариантов срока нет, и
-- «без срока» остаётся штатным режимом, а не пропуском данных.
alter table public.variants add column if not exists deadline date;

comment on column public.variants.deadline is
  'Срок сдачи варианта (дата, настенная). NULL — без срока.';
